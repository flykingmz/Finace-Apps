                  <td>Income</td>
                </tr>
                <tr>
                  <td>Mining profits</td>
                  <td>Income</td>
                </tr>
                <tr>
                  <td>Day trading</td>
                  <td>Income</td>
                </tr>
              </tbody>
            </table>
          </div>

          <h3>Why This Matters</h3>
          <p class="highlight">👉 Income is taxed at your full marginal rate</p>
          <p>Unlike CGT, there's no 50% discount.</p>

          <h3>Double Tax Effect</h3>
          <p>You may be taxed twice:</p>
          <ol>
            <li>When you receive crypto (income)</li>
            <li>When you sell it later (capital gains)</li>
          </ol>

          <h3>Practical Insight</h3>
          <p>This is where many people accidentally underestimate their tax liability.</p>

