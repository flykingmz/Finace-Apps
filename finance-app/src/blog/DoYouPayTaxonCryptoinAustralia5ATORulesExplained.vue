          <p>If there's one rule you can't ignore, it's this one.</p>

          <h3>What the ATO Requires</h3>
          <p>You must track:</p>
          <ul>
            <li>transaction dates</li>
            <li>value in AUD at the time</li>
            <li>wallet addresses</li>
            <li>exchange records</li>
            <li>fees</li>
          </ul>

