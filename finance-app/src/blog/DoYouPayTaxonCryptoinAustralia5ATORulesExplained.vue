                  <td>$2,500</td>
                </tr>
              </tbody>
            </table>
          </div>
          <p class="highlight">👉 This is one of the biggest tax advantages available.</p>

          <h3>Practical Insight</h3>
          <p>A lot of people overtrade and lose this benefit.</p>
          <p>Sometimes, simply holding longer can reduce your tax bill significantly.</p>

          <h2>4️⃣ Rule #3: Crypto-to-Crypto Trades Are Taxable</h2>
          
          <p>This is where many investors get caught off guard.</p>

          <h3>The Misconception</h3>
          <p class="quote">"I didn't cash out, so I don't owe tax."</p>

          <h3>The Reality</h3>
          <p>Under <strong>Australian Taxation Office</strong> rules:</p>
          <p class="highlight">👉 Trading BTC for ETH is a taxable event</p>

          <h3>Example</h3>
          <div class="table-wrap">
            <table>
              <thead>
                <tr>
                  <th>Action</th>
                  <th>Result</th>
                </tr>
              </thead>
              <tbody>
                <tr>
                  <td>Buy BTC at $20,000</td>
                  <td>Cost base</td>
                </tr>
                <tr>
                  <td>Swap at $30,000</td>
                  <td>$10,000 gain</td>
                </tr>
              </tbody>
            </table>
          </div>
          <p class="highlight">👉 That $10,000 gain is taxable—even without AUD involved.</p>

          <h3>Why This Matters</h3>
          <p>If you're actively trading:</p>
          <ul>
            <li>you may trigger dozens of taxable events</li>
            <li>your tax bill can grow faster than expected</li>
          </ul>

          <h3>Practical Tip</h3>
          <p>Before making frequent trades, ask:</p>
          <p class="highlight">👉 "Is this worth the tax impact?"</p>

          <h2>5️⃣ Rule #4: Some Crypto Activity Is Taxed as Income</h2>
          
          <p>Not all crypto is treated the same.</p>
          <p>In some cases, you're not dealing with capital gains—you're dealing with income tax.</p>

          <h3>When It's Income</h3>
          <p>You may owe income tax if you:</p>
          <ul>
            <li>trade frequently (business activity)</li>
            <li>mine crypto</li>
            <li>receive staking rewards</li>
            <li>earn airdrops (in certain cases)</li>
          </ul>

          <h3>Example</h3>
          <div class="table-wrap">
            <table>
