          <h1>Do You Pay Tax on Crypto in Australia? 5 ATO Rules Explained</h1>
          
          <h2>Introduction</h2>
          
          <p>If you've bought, traded, or even just experimented with crypto in Australia, you've probably asked yourself at some point:</p>
          <p class="highlight">👉 "Do I actually have to pay tax on this?"</p>
          
          <p>Short answer: yes, in most cases.</p>
          
          <p>Longer answer—and the one that actually matters—is this:</p>
          <p class="highlight">👉 When do you pay tax, how much, and under which rules?</p>
          
          <p>Because under the framework set by the <strong>Australian Taxation Office (ATO)</strong>, crypto isn't treated like cash—it's treated as property. And that changes everything.</p>
          
          <p>This guide walks through the 5 key ATO rules that determine how your crypto is taxed, with real-world examples and practical strategies to help you stay compliant—and avoid overpaying.</p>

          <h2>1️⃣ Executive Summary</h2>
          
          <ul>
            <li>Crypto is taxed as an asset, not currency</li>
            <li>Most transactions trigger Capital Gains Tax (CGT)</li>
            <li>Some activities (trading, staking, mining) are taxed as income</li>
            <li>Crypto-to-crypto swaps are taxable events</li>
            <li>Proper recordkeeping is essential to avoid penalties</li>
          </ul>

          <h2>2️⃣ Rule #1: Crypto Is an Asset (Not Money)</h2>
          
          <p>This is the foundation of everything.</p>
          <p>According to the <strong>Australian Taxation Office</strong>:</p>
          <p class="highlight">👉 Crypto is treated as property for tax purposes</p>

          <h3>Why This Matters</h3>
          <p>It means:</p>
          <ul>
            <li>You don't get "currency" treatment</li>
            <li>Every disposal is potentially taxable</li>
            <li>Gains fall under Capital Gains Tax (CGT) rules</li>
          </ul>

          <h3>What Counts as a Disposal?</h3>
          <p>You trigger a CGT event when you:</p>
          <ul>
            <li>sell crypto for AUD</li>
            <li>trade one crypto for another</li>
            <li>spend crypto</li>
            <li>gift crypto</li>
          </ul>

          <h3>Example</h3>
          <div class="table-wrap">
            <table>
              <thead>
                <tr>
                  <th>Action</th>
                  <th>Taxable?</th>
                </tr>
              </thead>
              <tbody>
                <tr>
                  <td>Buy Bitcoin</td>
                  <td>❌ No</td>
                </tr>
                <tr>
                  <td>Sell Bitcoin</td>
                  <td>✅ Yes</td>
                </tr>
                <tr>
                  <td>Swap BTC → ETH</td>
                  <td>✅ Yes</td>
                </tr>
              </tbody>
            </table>
          </div>
          <p class="highlight">👉 Even if no cash hits your bank account, tax may still apply.</p>

          <h2>3️⃣ Rule #2: Capital Gains Tax Applies to Most Investors</h2>
          
          <p>For most everyday investors, crypto profits are taxed under CGT.</p>

          <h3>How It's Calculated</h3>
          
          <div class="formula-block">
            <p><strong>Capital Gain = Sale Price – Cost Base</strong></p>
          </div>

          <h3>Example</h3>
          <div class="table-wrap">
            <table>
              <thead>
                <tr>
                  <th>Item</th>
                  <th>Value</th>
                </tr>
              </thead>
              <tbody>
                <tr>
                  <td>Buy ETH</td>
                  <td>$3,000</td>
                </tr>
                <tr>
                  <td>Sell ETH</td>
                  <td>$8,000</td>
                </tr>
                <tr>
                  <td><strong>Gain</strong></td>
                  <td><strong>$5,000</strong></td>
                </tr>
              </tbody>
            </table>
          </div>

          <h3>The 50% Discount Rule</h3>
          <p>If you hold crypto for more than 12 months:</p>
          <p class="highlight">👉 You may get a 50% CGT discount</p>

          <h3>Example with Discount</h3>
          <div class="table-wrap">
            <table>
              <thead>
                <tr>
                  <th>Gain</th>
                  <th>Taxable</th>
                </tr>
              </thead>
