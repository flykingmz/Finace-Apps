          <p>Yes.</p>
          <p>The <strong>Australian Taxation Office</strong> uses:</p>
          <ul>
            <li>exchange data sharing</li>
            <li>blockchain analysis</li>
            <li>international reporting systems</li>
          </ul>
          <p class="highlight">👉 Assuming "they won't know" is a bad strategy.</p>

