            <li>Consider tax impact before frequent trading</li>
          </ul>

          <h2>Rule #3: Understand the UK Share Pooling Rules</h2>
          
          <p>The UK uses a unique system called share pooling (Section 104).</p>
          <p>This makes crypto tax calculations more complex than simple FIFO.</p>

          <h3>The 3 Key Rules</h3>
          <ol>
            <li><strong>Same-Day Rule</strong> – Assets bought and sold on the same day are matched first.</li>
            <li><strong>30-Day Rule (Bed and Breakfast)</strong> – Assets repurchased within 30 days are matched with the sale.</li>
            <li><strong>Section 104 Pool</strong> – All other assets are averaged into a pooled cost basis.</li>
          </ol>

          <h3>Why this matters</h3>
          <p>These rules:</p>
          <ul>
            <li>prevent tax avoidance</li>
            <li>affect your cost basis significantly</li>
          </ul>

          <h3>Strategy</h3>
          <ul>
            <li>Avoid quick buy-back trades if trying to realize losses</li>
            <li>Use a calculator that supports HMRC pooling rules</li>
          </ul>

